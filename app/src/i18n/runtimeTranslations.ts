export const translateRuntimeText = (source: string, language: RuntimeLanguage): string => {
  if (language === 'en') {
    return source;
  }
  const normalized = normalize(source);
  if (!normalized) {
    return source;
  }

  const resolved = dictionary[language][normalized];
  if (!resolved) {
    return source;
  }

  if (source === normalized) {
    return resolved;
  }

  return source.replace(normalized, resolved);
};
